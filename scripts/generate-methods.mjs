import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// src/lib/api/methods.generated.ts: the methods the screens' api() may name, as a union type. They are the methods of
// the local API's catalog (electron/api-catalog.cjs METHODS, from which the REST routes, the MCP tools and the manuals
// are made) and those only the screens call: the methods of the screens' allow-list (electron/main.cjs ALLOWED) beyond
// the catalog, such as the import boxes' own jobs and the file pickers. `--check` writes nothing and fails when the
// committed file differs from what it would write; tests/methods.test.cjs checks the same, and also that every method
// the screens call is allowed and handled.

const require = createRequire(import.meta.url);
export const projectRoot = fileURLToPath(new URL('../', import.meta.url));
export const OUTPUT = path.join(projectRoot, 'src', 'lib', 'api', 'methods.generated.ts');

// The methods of main.cjs's ALLOWED set, read from its source, as main.cjs runs only inside Electron.
export function allowedMethods(
  source = readFileSync(path.join(projectRoot, 'electron', 'main.cjs'), 'utf8'),
) {
  const block = /const ALLOWED = new Set\(\[([\s\S]*?)\]\);/.exec(source);
  if (!block) throw new Error('electron/main.cjs에서 ALLOWED 목록을 찾지 못했습니다.');
  return [...block[1].replace(/\/\/.*$/gm, '').matchAll(/'([^'\\]+)'/g)].map((match) => match[1]);
}

export const catalogMethods = () => Object.keys(require('../electron/api-catalog.cjs').METHODS);

const union = (names) => names.map((name) => `  | '${name}'`).join('\n');

export async function render() {
  const catalog = [...new Set(catalogMethods())].sort();
  const listed = new Set(catalog);
  const screens = [...new Set(allowedMethods())].filter((name) => !listed.has(name)).sort();
  const source = `// Generated by scripts/generate-methods.mjs from electron/api-catalog.cjs (METHODS) and electron/main.cjs (ALLOWED):
// run npm run generate:methods after changing either, rather than editing this file. tests/methods.test.cjs fails while
// it is not current.

// The methods of the local API's catalog, which AI tools call too.
export type CatalogMethod =
${union(catalog)};

// The methods only the screens call: those the main process allows them beyond the catalog.
export type ScreenMethod =
${union(screens)};

export type Method = CatalogMethod | ScreenMethod;
`;
  const prettier = require('prettier');
  const options = { ...(await prettier.resolveConfig(OUTPUT)), parser: 'typescript' };
  return prettier.format(source, options);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const text = await render();
  const name = path.relative(projectRoot, OUTPUT).replaceAll('\\', '/');
  if (process.argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error(
        `${name}이(가) 최신이 아닙니다. npm run generate:methods를 실행한 뒤 커밋하세요.`,
      );
      process.exit(1);
    }
    console.log(`${name}이(가) 최신입니다.`);
  } else {
    writeFileSync(OUTPUT, text);
    console.log(`${name}을(를) 갱신했습니다.`);
  }
}
